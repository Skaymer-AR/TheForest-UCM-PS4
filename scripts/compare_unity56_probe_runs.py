#!/usr/bin/env python3
"""Compare two real Unity 5.6.6f2 probe output directories.

This tool compares snapshots, build target, declared AssetBundle dependencies,
and byte hashes for every reported artifact. If AssetsTools.NET reports were
generated in both directories, it also compares their object PathIDs, class
IDs, raw-object hashes, external files, and PPtr summaries. It never executes
Unity or claims the supplied directories were generated by an Editor.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_unity_editor_probe import _safe_file, _sha256, validate_editor_report  # noqa: E402


def _reported_file_hashes(root: Path, report: dict) -> dict[str, str]:
    result = {"unity-editor-report.json": _sha256(root / "unity-editor-report.json")}
    for variant in report["variants"]:
        for role in ("scene", "prefab", "bundle"):
            path = variant[role + "Path"]
            result[path] = _sha256(_safe_file(root, path))
    return result


def _assetstools_rows(root: Path) -> dict[str, dict] | None:
    report_dir = root / "assets-tools"
    paths = sorted(report_dir.glob("*.json")) if report_dir.is_dir() else []
    if not paths:
        return None
    result = {}
    for path in paths:
        row = json.loads(path.read_text(encoding="utf-8"))
        result[path.stem] = {
            "formatVersion": row.get("formatVersion"),
            "unityVersion": row.get("unityVersion"),
            "typeTreeEnabled": row.get("typeTreeEnabled"),
            "assetFileBytes": row.get("assetFileBytes"),
            "assetFileName": row.get("assetFileName"),
            "externalFiles": row.get("externalFiles"),
            "objects": row.get("objects"),
            "gameObjects": row.get("gameObjects"),
            "transforms": row.get("transforms"),
            "monoBehaviours": row.get("monoBehaviours"),
        }
    return result


def compare_runs(first: Path, second: Path) -> dict:
    first = first.resolve()
    second = second.resolve()
    left = validate_editor_report(first)
    right = validate_editor_report(second)
    semantic_fields = ("unityVersion", "serializationMode", "buildTarget",
                       "expectedSerializedFileFormat", "outputKinds")
    semantic_differences = [key for key in semantic_fields if left.get(key) != right.get(key)]
    left_variants = {row["name"]: row for row in left["variants"]}
    right_variants = {row["name"]: row for row in right["variants"]}
    for name in left_variants:
        a, b = left_variants[name], right_variants[name]
        for key in ("changedField", "snapshot", "bundleDependencies"):
            if a.get(key) != b.get(key):
                semantic_differences.append(name + "." + key)

    left_hashes = _reported_file_hashes(first, left)
    right_hashes = _reported_file_hashes(second, right)
    hash_differences = sorted(
        name for name in set(left_hashes) | set(right_hashes)
        if left_hashes.get(name) != right_hashes.get(name))

    left_assets = _assetstools_rows(first)
    right_assets = _assetstools_rows(second)
    if (left_assets is None) != (right_assets is None):
        semantic_differences.append("AssetsTools.NET reports present in only one run")
    elif left_assets is not None and left_assets != right_assets:
        semantic_differences.append("AssetsTools.NET object/PPtr reports differ")

    return {
        "schemaVersion": 1,
        "unityVersion": left.get("unityVersion"),
        "semanticEquivalent": not semantic_differences,
        "allArtifactHashesIdentical": not hash_differences,
        "assetsToolsRowsCompared": left_assets is not None and right_assets is not None,
        "metaGuidFilesCompared": False,
        "metaGuidFilesNote": "Unity allocates .meta asset identity GUIDs per scratch project; serialized scene/prefab/bundle bytes are compared instead.",
        "semanticDifferences": sorted(semantic_differences),
        "artifactHashDifferences": hash_differences,
        "firstRunArtifactCount": len(left_hashes),
        "secondRunArtifactCount": len(right_hashes),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("first_run", type=Path)
    parser.add_argument("second_run", type=Path)
    parser.add_argument("--report", type=Path, help="also write comparison JSON here")
    args = parser.parse_args()
    try:
        result = compare_runs(args.first_run, args.second_run)
        text = json.dumps(result, indent=2, sort_keys=True) + "\n"
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(text, encoding="utf-8")
        print(text, end="")
        if not result["semanticEquivalent"] or not result["allArtifactHashesIdentical"]:
            print("Unity probe reproducibility: DIFFERENCES FOUND", file=sys.stderr)
            return 1
        print("Unity probe reproducibility: PASS (byte-identical outputs)")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print("Unity probe comparison failed: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

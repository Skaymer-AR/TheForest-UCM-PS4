from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from validate_unity_editor_probe import (  # noqa: E402
    BASELINE,
    EXPECTED_VARIANTS,
    SNAPSHOT_KEYS,
    _safe_file,
    _verify_unity_yaml,
    changed_snapshot_fields,
    validate_editor_report,
)


class UnityEditorProbeValidatorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)

    def tearDown(self):
        self.temp.cleanup()

    def test_missing_editor_report_is_not_reported_as_a_pass(self):
        with self.assertRaisesRegex(ValueError, "no Editor result can be claimed"):
            validate_editor_report(self.root)

    def test_report_must_claim_exact_real_editor_and_reload(self):
        path = self.root / "unity-editor-report.json"
        path.write_text(json.dumps({
            "generatedBy": "test stub",
            "unityVersion": "5.6.6f2",
            "serializationMode": "ForceText",
            "syntheticOnly": True,
            "capturedAfterSaveAndReload": True,
        }), encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "not marked as generated by Unity Editor"):
            validate_editor_report(self.root)

    def test_snapshot_delta_detects_one_serialized_field(self):
        before = dict(BASELINE)
        after = dict(BASELINE)
        after["intValue"] = 202
        self.assertEqual(set(before), SNAPSHOT_KEYS)
        self.assertEqual(changed_snapshot_fields(before, after), {"intValue"})

    def test_snapshot_delta_detects_unintended_second_field(self):
        before = dict(BASELINE)
        after = dict(BASELINE)
        after["intValue"] = 202
        after["boolValue"] = False
        self.assertEqual(changed_snapshot_fields(before, after), {"intValue", "boolValue"})

    def test_snapshot_schema_rejects_missing_or_extra_fields(self):
        before = dict(BASELINE)
        del before["mode"]
        with self.assertRaisesRegex(ValueError, "snapshot field set"):
            changed_snapshot_fields(before, dict(BASELINE))
        before = dict(BASELINE)
        before["madeUp"] = 7
        with self.assertRaisesRegex(ValueError, "snapshot field set"):
            changed_snapshot_fields(before, dict(BASELINE))

    def test_artifact_path_cannot_escape_output(self):
        with self.assertRaisesRegex(ValueError, "escapes"):
            _safe_file(self.root, "../outside.asset")

    def test_non_unity_yaml_is_rejected(self):
        path = self.root / "not-a-scene.unity"
        path.write_text("%YAML 1.1\nGameObject: fake\n", encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "not a ForceText Unity"):
            _verify_unity_yaml(path, dict(BASELINE))

    def test_fixture_yaml_shape_is_only_a_parser_contract(self):
        path = self.root / "synthetic-contract-sample.unity"
        path.write_text(
            "%YAML 1.1\n%TAG !u! tag:unity3d.com,2011:\n"
            "--- !u!1 &1\nGameObject: UCM_SERIALIZATION_PROBE_ROOT\n"
            "--- !u!4 &2\nTransform: {}\n"
            "--- !u!114 &3\nMonoBehaviour:\n"
            "  intValue: 101\n  boolValue: 1\n  floatValue: 1.25\n"
            "  stringValue: baseline\n  mode: 0\n  vectorValue: {}\n"
            "  colorValue: {}\n  referenceTarget: {fileID: 4}\n"
            "  states: []\n  firstState: Closed\n  nestedActionLabel: Observe\n"
            "  referenceName: SyntheticTargetA\n",
            encoding="utf-8")
        _verify_unity_yaml(path, dict(BASELINE))
        # This test checks a parser contract only; the sample is not Editor output.


if __name__ == "__main__":
    unittest.main()
